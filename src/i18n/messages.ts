export const messageCatalog = { en, zh } as const;

export type MessageParams = Record<string, string | number | undefined>;

export function translate(locale: UiLanguage, key: MessageKey, params?: MessageParams): string {
  const table = messageCatalog[locale] ?? messageCatalog.en;
  let text: string = table[key] ?? messageCatalog.en[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, value === undefined ? '' : String(value));
    }
  }
  return text;
}
